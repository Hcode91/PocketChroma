// Standalone handheld system, adapted from MAME's monon_color driver.
#pragma once
#include "axc51.h"
#include "spi_flash.h"

namespace chroma {

enum Button : uint32_t
{
	BTN_UP = 1 << 0, BTN_DOWN = 1 << 1, BTN_LEFT = 1 << 2, BTN_RIGHT = 1 << 3,
	BTN_A = 1 << 4, BTN_B = 1 << 5, BTN_L = 1 << 6, BTN_R = 1 << 7,
	BTN_MENU = 1 << 8, BTN_PAUSE = 1 << 9,
};

class System
{
public:
	static constexpr int WIDTH = 320;
	static constexpr int HEIGHT = 240;
	static constexpr int CPU_CLOCK = 48000000;   // MAME uses 96MHz/2
	static constexpr int AUDIO_RATE = 32000;

	System();

	// boot ROM: 8KB AX208 internal ROM supplied by the user
	bool load_bios(const uint8_t *data, size_t size);
	// cart: raw SPI flash dump (power of two, typically 16MB)
	bool load_cart(const uint8_t *data, size_t size);
	void reset();

	// run for 1/fps of a second; writes audio into internal buffer
	void run_frame(int fps = 60);

	void set_buttons(uint32_t b) { m_buttons = b; }

	const uint32_t *framebuffer() const { return m_vidbuffer.data(); } // ARGB8888, 320x240
	// int16 mono samples generated by the last run_frame()
	const std::vector<int16_t> &audio() const { return m_audio; }

	// save area (0x50000-0x5ffff of the flash)
	static constexpr uint32_t SAVE_BASE = 0x50000, SAVE_SIZE = 0x10000;
	const uint8_t *save_data() const { return m_flash.data() + SAVE_BASE; }
	bool load_save(const uint8_t *data, size_t size);
	bool save_dirty() { bool d = m_spi.m_dirty; m_spi.m_dirty = false; return d; }

	std::vector<uint8_t> save_state();
	bool load_state(const std::vector<uint8_t> &s);

	bool bios_loaded() const { return m_bios_ok; }

private:
	ax208_cpu_device m_cpu;
	spi_flash m_spi;
	std::vector<uint8_t> m_flash;
	uint8_t m_musicrom[0x1000];
	bool m_bios_ok = false;

	uint32_t m_buttons = 0;

	// timing
	int64_t m_cycle_accum = 0;
	int64_t m_timer0_ctr = 0, m_dac_ctr = 0, m_audio_ctr = 0;
	int16_t m_dac_level = 0;
	std::vector<int16_t> m_audio;
	int32_t m_hp_prev_in = 0, m_hp_prev_out = 0;

	// video
	uint32_t m_linebuf[HEIGHT];
	std::vector<uint32_t> m_vidbuffer;
	int16_t m_bufpos_y;
	uint32_t m_bufpos_x;
	uint8_t m_storeregs[0x20];
	uint8_t m_dacbyte;
	uint8_t m_out4data, m_out3data, m_out2data, m_out1data, m_out0data;
	uint8_t m_curpal[0x800 * 3];

	// music MCU serial link
	bool m_music_direction_iswrite;
	uint16_t m_music_latch;
	uint8_t m_music_bitpos, m_music_response_bit, m_music_bits_in_needed;

	template <typename F> void serialize(F &&f);

	uint8_t controls(int n) const;
	uint8_t read_current_inputs();
	uint8_t in0_r(); uint8_t in1_r(); uint8_t in2_r(); uint8_t in3_r(); uint8_t in4_r();
	void out0_w(uint8_t d); void out1_w(uint8_t d); void out2_w(uint8_t d); void out3_w(uint8_t d); void out4_w(uint8_t d);
	void dacout0_w(uint8_t d);
	uint8_t spibuf_r() { return m_spi.read(); }
	void spibuf_w(uint8_t d) { m_spi.write(d); }
	uint8_t read_from_video_device();
	void write_to_video_device(uint8_t data);
	void get_music_command_bit(uint8_t bit);
	void do_draw_inner(int pal_to_use, int start, int step, int pixmask, int amount);
	void do_draw(int amount, int pal_to_use);
	void do_palette(int amount, int pal_to_use);
};

} // namespace chroma
